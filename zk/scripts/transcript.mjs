// Writes setup/TRANSCRIPT.md from the ceremony log, and copies the final zkey and verification key into setup/ with their
// sha256. Called by scripts/ceremony.sh: node scripts/transcript.mjs <ceremony dir> <build dir> <slot> <blockhash> <beacon hex>
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const [C, B, slot, hash58, beacon] = process.argv.slice(2);
const here = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const setup = path.join(here, 'setup');
fs.mkdirSync(setup, { recursive: true });
const sha = f => crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex');
const log = fs.readFileSync(path.join(C, 'phase1.log'), 'utf8') + '\n' + fs.readFileSync(path.join(C, 'phase2.log'), 'utf8');
const logClean = log.replace(/\\n/g, '\n');
fs.copyFileSync(path.join(C, 'pof_final.zkey'), path.join(setup, 'pof_final.zkey'));
fs.copyFileSync(path.join(C, 'verification_key.json'), path.join(setup, 'verification_key.json'));
fs.copyFileSync(path.join(B, 'pof_js/pof.wasm'), path.join(setup, 'pof.wasm'));
const files = ['pof_final.zkey', 'verification_key.json', 'pof.wasm'].map(f => ({ f, size: fs.statSync(path.join(setup, f)).size, sha: sha(path.join(setup, f)) }));
const r1cs = { size: fs.statSync(path.join(B, 'pof.r1cs')).size, sha: sha(path.join(B, 'pof.r1cs')) };
const ptau = { size: fs.statSync(path.join(C, 'pot_final.ptau')).size, sha: sha(path.join(C, 'pot_final.ptau')) };
// the contribution hashes snarkjs printed, in order
const hashes = [];
const lines = logClean.split('\n');
for (let i = 0; i < lines.length; i++) {
  if (/Contribution Hash|contribution hash|Circuit Hash|Circuit hash/i.test(lines[i])) {
    const block = [lines[i].trim()];
    for (let j = i + 1; j < i + 5 && j < lines.length && /^[\s\[\]a-zA-Z:]*\s*[0-9a-f]{8} [0-9a-f]{8}/.test(lines[j].replace(/^.*?(?=[0-9a-f]{8} )/, '')); j++) block.push(lines[j].trim());
    hashes.push(block.join('\n'));
  }
}
const md = `# POF zk: the development trusted setup (transcript)

**This is a development setup.** One machine made every contribution, so whoever ran it could have kept the toxic waste and
could forge proofs for this key. It is good for local tests and devnet only. Before any mainnet use, the plan in
\`docs-src/zk.md\` ("The public ceremony") replaces it: phase 1 from the Perpetual Powers of Tau, phase 2 opened to outside
contributors, the final key's hash published before \`certify_zk\` is enabled.

Generated by \`scripts/ceremony.sh\` on ${new Date().toISOString().slice(0, 10)}.

## Inputs
| what | bytes | sha256 |
|---|---|---|
| \`build/pof.r1cs\` (circuits/pof.circom, circom 2.2.2 --O2) | ${r1cs.size} | \`${r1cs.sha}\` |
| \`pot_final.ptau\` (phase 1 output, BN254 2^17, kept out of git) | ${ptau.size} | \`${ptau.sha}\` |

## Outputs (in \`setup/\`)
| file | bytes | sha256 |
|---|---|---|
${files.map(x => `| \`${x.f}\` | ${x.size} | \`${x.sha}\` |`).join('\n')}

## The beacons
Each phase ends with a beacon contribution (2^10 iterations) whose value is public and was fixed after the random
contributions of that phase: \`sha256\` of the 32 bytes of a finalized Solana mainnet blockhash. Anyone can read those blocks
again (\`getBlock <slot>\`):
${logClean.split('\n').filter(l => l.startsWith('beacon:')).map(l => '- ' + l.replace(/^beacon: /, '')).join('\n')}

## Steps
1. Phase 1: \`powersoftau new bn128 17\`, two contributions with 64 bytes from \`/dev/urandom\` each (not stored), the beacon,
   \`prepare phase2\`, \`powersoftau verify\`.
2. Phase 2: \`groth16 setup\` over the r1cs, two contributions (random, not stored), the beacon, \`zkey verify\` against the r1cs
   and the phase 1 output, \`zkey export verificationkey\`.

How to check it yourself: rebuild the r1cs (\`zsh scripts/build.sh\`, same sha256 as above), then
\`snarkjs zkey verify build/pof.r1cs pot_final.ptau setup/pof_final.zkey\`. The dev ptau is not distributed (about 150 MB); a
verifier without it can still check that the r1cs hash matches and that \`verification_key.json\` is the one the zkey exports
(\`snarkjs zkey export verificationkey\`), and that the program's embedded key equals it (\`onchain/vk.rs\` is generated from it).

## Contribution hashes (as snarkjs printed them)
\`\`\`
${hashes.join('\n\n')}
\`\`\`

## The full log
\`\`\`
${logClean.replace(/-e=[0-9a-f]{20,}/g, '-e=<discarded>').split('\n').filter(l => !/^\[DEBUG\]/.test(l)).join('\n').trim()}
\`\`\`
`;
fs.writeFileSync(path.join(setup, 'TRANSCRIPT.md'), md);
console.log('transcript written;', files.map(x => `${x.f} ${(x.size / 1e6).toFixed(1)} MB`).join(', '));
