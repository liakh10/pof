// setup/verification_key.json -> onchain/src/vk.rs: the verifying key as big-endian byte constants for groth16.rs, and its
// sha256 (VK_HASH, what ZkConfig.vk_hash and /docs show). Run: node scripts/vk-rs.mjs
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const vk = JSON.parse(fs.readFileSync(path.join(root, 'setup/verification_key.json'), 'utf8'));
const be = v => { const h = BigInt(v).toString(16).padStart(64, '0'); return Buffer.from(h, 'hex'); };
const g1 = p => Buffer.concat([be(p[0]), be(p[1])]);
const g2 = p => Buffer.concat([be(p[0][1]), be(p[0][0]), be(p[1][1]), be(p[1][0])]);
const arr = b => '[' + [...b].map(x => '0x' + x.toString(16).padStart(2, '0')).join(', ') + ']';
const ic = vk.IC.map(g1);
const all = Buffer.concat([g1(vk.vk_alpha_1), g2(vk.vk_beta_2), g2(vk.vk_gamma_2), g2(vk.vk_delta_2), ...ic]);
const hash = crypto.createHash('sha256').update(all).digest();
const out = `//! GENERATED by scripts/vk-rs.mjs from setup/verification_key.json (the DEVELOPMENT setup, setup/TRANSCRIPT.md). Do not edit.
//! VK_HASH = sha256(alpha ‖ beta ‖ gamma ‖ delta ‖ IC_0 ‖ … ‖ IC_${vk.nPublic}) = ${hash.toString('hex')}
pub const NPUB: usize = ${vk.nPublic};
pub const VK_HASH: [u8; 32] = ${arr(hash)};
pub const VK_ALPHA_G1: [u8; 64] = ${arr(g1(vk.vk_alpha_1))};
pub const VK_BETA_G2: [u8; 128] = ${arr(g2(vk.vk_beta_2))};
pub const VK_GAMMA_G2: [u8; 128] = ${arr(g2(vk.vk_gamma_2))};
pub const VK_DELTA_G2: [u8; 128] = ${arr(g2(vk.vk_delta_2))};
pub const VK_IC: [[u8; 64]; ${ic.length}] = [
${ic.map(b => '    ' + arr(b) + ',').join('\n')}
];
`;
fs.writeFileSync(path.join(root, 'onchain/src/vk.rs'), out);
console.log('onchain/src/vk.rs: nPublic', vk.nPublic, 'VK_HASH', hash.toString('hex'));
