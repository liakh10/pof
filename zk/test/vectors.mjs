// Writes onchain/test/vectors.json: real proofs (1 and 4 notes) with their 17 public inputs, as the program takes them
// (proof 256 bytes with A negated, inputs 32-byte big-endian), for the native Rust tests of onchain/src/groth16.rs.
// Run: node test/vectors.mjs
import fs from 'node:fs';
import path from 'node:path';
import * as snarkjs from 'snarkjs';
import * as Z from '../js/zk.js';
import { scenario, WASM, ZKEY, ONE_SOL, root } from './fixtures.mjs';

const out = [];
for (const s of [await scenario({ amounts: [3n * ONE_SOL] }), await scenario({ amounts: [4n, 3n, 2n, 1n].map(x => x * ONE_SOL), minAmount: 10n * ONE_SOL, ctx: 99n })]) {
  const b = Z.buildInputs(s.P, s);
  const { proof, publicSignals } = await snarkjs.groth16.fullProve(b.input, WASM, ZKEY);
  out.push({ proof: Z.hex(Z.proofBytes(proof)), inputs: publicSignals.map(x => Z.hex(Z.be32(BigInt(x)))) });
}
fs.writeFileSync(path.join(root, 'onchain/test/vectors.json'), JSON.stringify({ note: 'generated by test/vectors.mjs with the development setup', proofs: out }, null, 1));
console.log('onchain/test/vectors.json:', out.length, 'proofs');
process.exit(0);
