// node tools/build.mjs: bundles src/spr-entry.js and src/web3-entry.js for the browser into dist/ (ESM, minified), copies
// the Poseidon WASM next to them, and fails when a file passes its gzip budget.
import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');
fs.mkdirSync(dist, { recursive: true });
const shim = path.join(root, 'src/hasher-shim.js');
const hasherAlias = { name: 'hasher-shim', setup(b) { b.onResolve({ filter: /^@lightprotocol\/hasher\.rs$/ }, a => (a.importer === shim ? undefined : { path: shim })); } };
const H0 = path.join(root, 'node_modules/@lightprotocol/hasher.rs/dist');
const crypto = await import('node:crypto');
const shaOf = f => crypto.createHash('sha256').update(fs.readFileSync(path.join(H0, f))).digest('hex');
const WASM_SHA = { simd: shaOf('hasher_wasm_simd_bg.wasm'), sisd: shaOf('light_wasm_hasher_bg.wasm') };
// the relay credit key and house ring each network's relayer uses (audit CR-01), pinned into the build from the file the
// Verifier publishes; a network without an entry cannot buy credits from this build
// it is read as COMMITTED (git show HEAD:…), so another agent's uncommitted key change never reaches a build
const pinsFile = path.join(root, '../verifier/lib/credit-pins.json');
const { execFileSync } = await import('node:child_process');
let pinsText = null;
try { pinsText = execFileSync('git', ['show', 'HEAD:verifier/lib/credit-pins.json'], { cwd: path.join(root, '..'), encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }); } catch {}
if (pinsText === null && fs.existsSync(pinsFile)) pinsText = fs.readFileSync(pinsFile, 'utf8');
if (pinsText !== null && fs.existsSync(pinsFile) && fs.readFileSync(pinsFile, 'utf8') !== pinsText) console.warn('note: verifier/lib/credit-pins.json has uncommitted changes; the build uses the committed version');
const CREDIT_PINS = pinsText ? JSON.parse(pinsText).networks || {} : {};
const common = { bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true, legalComments: 'none', define: { global: 'globalThis', 'process.env.NODE_ENV': '"production"', __POF_WASM_SHA256__: JSON.stringify(WASM_SHA), __POF_CREDIT_PINS__: JSON.stringify(CREDIT_PINS) }, logLevel: 'warning' };
for (const f of fs.readdirSync(dist)) if (/^chunk-.*\.js$/.test(f)) fs.rmSync(path.join(dist, f));
const spr = await esbuild.build({ ...common, entryPoints: { spr: path.join(root, 'src/spr-entry.js'), 'spr-spend': path.join(root, 'src/spend-entry.js') }, outdir: dist, splitting: true, chunkNames: 'chunk-[hash]', plugins: [hasherAlias], metafile: true });
await esbuild.build({ ...common, entryPoints: [path.join(root, 'src/web3-entry.js')], outfile: path.join(dist, 'web3.js') });
fs.writeFileSync(path.join(dist, 'pins.js'), `/* generated by tools/build.mjs from verifier/lib/credit-pins.json: the relay credit keys and house rings this build trusts (audit CR-01) */\nexport const CREDIT_PINS = Object.freeze(${JSON.stringify(CREDIT_PINS, null, 1)});\n`);
// the blind RSA credits, byte for byte the Verifier's own module (verifier/lib/blind.mjs, zero dependencies)
fs.copyFileSync(path.join(root, '../verifier/lib/blind.mjs'), path.join(dist, 'blind.mjs'));
const H = path.join(root, 'node_modules/@lightprotocol/hasher.rs/dist');
fs.copyFileSync(path.join(H, 'hasher_wasm_simd_bg.wasm'), path.join(dist, 'hasher-simd.wasm'));
fs.copyFileSync(path.join(H, 'light_wasm_hasher_bg.wasm'), path.join(dist, 'hasher.wasm'));
// budgets in gzip bytes: what a first visit downloads
const chunks = fs.readdirSync(dist).filter(f => /^chunk-.*\.js$/.test(f));
const BUDGET = { 'spr.js': 200_000, 'spr-spend.js': 260_000, ...Object.fromEntries(chunks.map(c => [c, 200_000])), 'web3.js': 110_000, 'hasher-simd.wasm': 440_000, 'hasher.wasm': 580_000 };
let over = false;
const rows = [];
for (const [f, max] of Object.entries(BUDGET)) {
  const b = fs.readFileSync(path.join(dist, f)); const gz = zlib.gzipSync(b, { level: 9 }).length;
  rows.push(`${f.padEnd(18)} ${String(b.length).padStart(9)} B  gzip ${String(gz).padStart(8)} B  budget ${max}`);
  if (gz > max) over = true;
}
fs.writeFileSync(path.join(dist, 'SIZES.txt'), rows.join('\n') + '\n' + `sha256 hasher-simd.wasm ${WASM_SHA.simd}\nsha256 hasher.wasm ${WASM_SHA.sisd}\n`);
console.log(rows.join('\n'));
if (process.argv.includes('--why')) { const ins = Object.entries(spr.metafile.outputs).find(([k]) => k.endsWith('spr.js'))[1].inputs; const by = {}; for (const [k, v] of Object.entries(ins)) { const m = k.match(/node_modules\/((@[^/]+\/)?[^/]+)/); const key = m ? m[1] : k; by[key] = (by[key] || 0) + v.bytesInOutput; } console.log(Object.entries(by).sort((a, b) => b[1] - a[1]).slice(0, 25)); }
if (over) { console.error('a file is over its budget'); process.exit(1); }
