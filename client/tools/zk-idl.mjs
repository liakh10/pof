// node tools/zk-idl.mjs: writes zk-idl.js (the zk build's IDL, program/idl/pof-zk.json at git HEAD, as an ES module the page can import)
// for zk-flow.js. test/zk-flow.test.mjs fails when the two differ, so rerun this after the program refreshes pof-zk.json.
// It reads the COMMITTED file (git HEAD): the tree is shared, and another agent's work in progress must not leak in.
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
export const committedZkIdl = () => JSON.parse(execFileSync('git', ['show', 'HEAD:program/idl/pof-zk.json'], { cwd: new URL('../..', import.meta.url).pathname, encoding: 'utf8', maxBuffer: 1 << 24 }));
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
const idl = committedZkIdl();
fs.writeFileSync(new URL('../zk-idl.js', import.meta.url), '/* generated by tools/zk-idl.mjs from program/idl/pof-zk.json (the zk build of pof); do not edit */\nexport default ' + JSON.stringify(idl) + ';\n');
console.log('zk-idl.js:', idl.instructions.length, 'instructions');
}
