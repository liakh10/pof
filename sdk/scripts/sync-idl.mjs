// Copy the program's committed IDLs into src/idl/*.ts so the SDK decodes exactly what the program writes.
// Usage: npm run sync-idl   (then npm test)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../../program");
const candidates = (name) => [
  path.join(root, "idl", `${name}.json`),
  path.join(root, "target", "idl", `${name}.json`),
];
const out = { pof: "POF_IDL", pof_gate: "POF_GATE_IDL", "pof-zk": "POF_ZK_IDL" };
let n = 0;
for (const [name, constName] of Object.entries(out)) {
  const src = candidates(name).find((p) => fs.existsSync(p));
  const file = path.join(here, "..", "src", "idl", `${name.replace("-", "_")}.ts`);
  if (!src) {
    if (name === "pof-zk") {
      // optional: the zk build's IDL; absent means the SDK ships without it
      fs.writeFileSync(file, `// No zk IDL in program/idl: the launch build has no zk instructions.\nexport const IDL_IS_DRAFT = false;\nexport const ${constName} = null;\n`);
      console.log("pof-zk: none (launch build only)");
      continue;
    }
    console.log(`${name}: no IDL found (looked in ${candidates(name).join(", ")}), keeping the current file`);
    continue;
  }
  const idl = JSON.parse(fs.readFileSync(src, "utf8"));
  const body =
    `// Generated by scripts/sync-idl.mjs from ${path.relative(path.resolve(here, ".."), src)}. Do not edit by hand.\n` +
    `export const IDL_IS_DRAFT = false;\n` +
    `export const ${constName} = ${JSON.stringify(idl, null, 2)} as const;\n`;
  fs.writeFileSync(file, body);
  console.log(`${name}: synced from ${src} (address ${idl.address}, version ${idl.metadata?.version})`);
  n++;
}
process.exit(n ? 0 : 0);
